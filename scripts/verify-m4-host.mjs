// Run in a fresh process. Uses the installed host loader, never a gateway or on-disk config.
import assert from 'node:assert/strict';
import {mkdtempSync,readFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
const root=mkdtempSync(join(tmpdir(),'fact-m4-host-'));
process.env.OPENCLAW_STATE_DIR=join(root,'state');
process.env.OPENCLAW_CONFIG_PATH=join(root,'absent-config.json');
const hostRoot=process.argv[2];
assert(hostRoot,'Usage: node scripts/verify-m4-host.mjs /app');
const {loadOpenClawPlugins}=await import(pathToFileURL(join(hostRoot,'dist/plugins/loader.js')));
const config={plugins:{enabled:true,allow:['fact-infra'],load:{paths:[resolve('.')]},entries:{'fact-infra':{enabled:true,config:{workRoot:join(root,'works'),indexPath:join(root,'index.db')}}}}};
const registry=loadOpenClawPlugins({config,workspaceDir:join(root,'workspace'),onlyPluginIds:['fact-infra'],cache:false});
const plugin=registry.plugins.find(p=>p.id==='fact-infra');
console.log(JSON.stringify({root,plugin,diagnostics:registry.diagnostics},null,2));
assert.equal(plugin?.status,'loaded');
const expected=['fact_create','fact_read','fact_plan','fact_record','fact_finish'];
assert.deepEqual([...plugin.toolNames].sort(),[...expected].sort());
const registrations=registry.tools.filter(t=>t.pluginId==='fact-infra');
const tools=registrations.flatMap(t=>{const tool=t.factory({config,workspaceDir:join(root,'workspace')});return Array.isArray(tool)?tool:[tool];}).filter(Boolean);
assert.deepEqual(tools.map(t=>t.name).sort(),[...expected].sort());
const create=await tools.find(t=>t.name==='fact_create').execute('m4-create',{action:'create',slug:'m4-smoke',kind:'project',purpose:'Isolated host verification',request_id:'m4-create'});
console.log('fact_create',JSON.stringify(create));
assert.equal(create.details.ok,true);
const overview=await tools.find(t=>t.name==='fact_read').execute('m4-read',{action:'overview'});
console.log('fact_read',JSON.stringify(overview));
assert.equal(overview.details.ok,true);
const manifest=JSON.parse(readFileSync('openclaw.plugin.json','utf8'));
assert.deepEqual([...manifest.contracts.tools].sort(),[...expected].sort());
console.log('PASS: host discovered exactly five tools; two host-wrapped execute calls succeeded; no gateway/config file used.');
